/**
 * Bills the bank never tells us about.
 *
 * Most fixed payments arrive as an alert email and get imported. A few never
 * do — OCBC sends nothing for a GIRO debit, so the monthly IRAS tax was
 * invisible to the app and had to be typed in by hand every month (and was
 * missed in October).
 *
 * The old recurring sync generated an auto-pay for EVERY recurring bucket and
 * was retired because it collided with those imports and made duplicates.
 * This is the narrow version: a bucket opts in by setting `autoLogDay`, so
 * only bills that produce no alert are ever generated.
 *
 * Safety: at most one row per (bucket, month), and the month is skipped
 * entirely if ANY expense already sits in that bucket — if the payment did
 * show up some other way, the real one wins and we add nothing.
 */

import { internalMutation } from "./_generated/server";
import { v } from "convex/values";
import type { Doc } from "./_generated/dataModel";

/** "YYYY-MM" for a timestamp, read in Singapore time. */
export function sgMonth(ts: number): string {
  return new Date(ts + 8 * 3600 * 1000).toISOString().slice(0, 7);
}

/** Day of the month in Singapore time. */
export function sgDay(ts: number): number {
  return new Date(ts + 8 * 3600 * 1000).getUTCDate();
}

/** Noon UTC on the given day, clamped to the length of that month. */
export function dayStamp(month: string, day: number): number {
  const year = Number(month.slice(0, 4));
  const mon = Number(month.slice(5, 7)) - 1;
  const last = new Date(Date.UTC(year, mon + 1, 0)).getUTCDate();
  return Date.UTC(year, mon, Math.min(Math.max(day, 1), last), 12, 0, 0);
}

async function logDue(
  ctx: any,
  bucket: Doc<"buckets">,
  now: number,
  dryRun: boolean,
  log: string[]
) {
  const day = bucket.autoLogDay;
  if (day === undefined || bucket.isActive === false) return;
  if (bucket.bucketMode !== "recurring") return;
  const amount = bucket.plannedAmount ?? 0;
  if (amount <= 0) return;

  const month = sgMonth(now);
  if (sgDay(now) < day) return; // not due yet this month

  // Anything already in this bucket this month means the payment is recorded
  // — imported, typed in, or generated on an earlier run. Leave it alone.
  const { start, end } = {
    start: dayStamp(month, 1) - 12 * 3600 * 1000,
    end: dayStamp(month, 31) + 12 * 3600 * 1000,
  };
  const existing = await ctx.db
    .query("expenses")
    .withIndex("by_bucket", (q: any) => q.eq("bucketId", bucket._id))
    .collect();
  const already = existing.find(
    (e: Doc<"expenses">) =>
      !e.superseded && e.date >= start && e.date <= end
  );
  if (already) {
    log.push(`${bucket.name} ${month}: already has "${already.note}" — skipped`);
    return;
  }

  const note = bucket.autoLogNote ?? bucket.name;
  log.push(`${bucket.name} ${month}: logged ${amount} as "${note}"`);
  if (dryRun) return;
  await ctx.db.insert("expenses", {
    userId: bucket.userId,
    bucketId: bucket._id,
    amount,
    date: dayStamp(month, day),
    note,
    isNecessary: true,
    isAutoGenerated: true,
    autoGeneratedForMonth: month,
    createdAt: Date.now(),
    updatedAt: Date.now(),
  });
}

/** Daily cron: log any bank-silent bill that has come due. */
export const runDaily = internalMutation({
  args: {},
  handler: async (ctx) => {
    const log: string[] = [];
    const now = Date.now();
    const buckets = await ctx.db.query("buckets").collect();
    for (const b of buckets) await logDue(ctx, b, now, false, log);
    if (log.length) console.log("autoLog:", log.join(" | "));
    return { count: log.length, changes: log };
  },
});

/** Same thing on demand, for checking before it runs for real. */
export const runNow = internalMutation({
  args: { dryRun: v.boolean() },
  handler: async (ctx, { dryRun }) => {
    const log: string[] = [];
    const now = Date.now();
    const buckets = await ctx.db.query("buckets").collect();
    for (const b of buckets) await logDue(ctx, b, now, dryRun, log);
    return { dryRun, count: log.length, changes: log };
  },
});

/** Turn it on (or off, with day undefined) for one bucket. */
export const setAutoLog = internalMutation({
  args: {
    bucketId: v.id("buckets"),
    day: v.optional(v.number()),
    note: v.optional(v.string()),
  },
  handler: async (ctx, { bucketId, day, note }) => {
    await ctx.db.patch(bucketId, { autoLogDay: day, autoLogNote: note });
    const b = await ctx.db.get(bucketId);
    return { name: b?.name, autoLogDay: b?.autoLogDay, autoLogNote: b?.autoLogNote };
  },
});
